// Usage: npx tsx scripts/build-companies-seed.ts [--industries-only]
// --industries-only writes only 20261109000600_company_industries.sql and leaves the applied 000200 migration untouched.
// Downloads four public files at pinned commit SHAs and writes supabase/migrations/20261109000200_seed_companies.sql.
// Sources (pinned):
//   Gsync/jobsync @ 8c20325c35dbf203334a270cef5aef446f06a774 (MIT, (c) 2024 gsync)
//     src/lib/scraper/{greenhouse,lever,ashby}/companies.json
//   datasets/s-and-p-500-companies @ 05c998c3e714b8dc9b621239bbdef92bccefc376 (ODC PDDL)
//     data/constituents.csv
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { normalizeCompany } from '../src/lib/companies/normalize';
import { stateFromLocation } from '../src/lib/onboarding/regions';
import { insertStatements, parseCsv, sqlText } from './seed-sql';

const JOBSYNC_SHA = '8c20325c35dbf203334a270cef5aef446f06a774';
const SP500_SHA = '05c998c3e714b8dc9b621239bbdef92bccefc376';

export type AtsEntry = { name: string; token: string; host?: string };
export type CompanyRow = {
  name: string;
  normalized_name: string;
  ats: 'greenhouse' | 'lever' | 'ashby' | 'unknown';
  ats_token: string | null;
  ats_meta: Record<string, string>;
  regions: string[];
  coverage: 'covered' | 'unknown';
};

export type SeedInput = {
  greenhouse: AtsEntry[];
  lever: AtsEntry[];
  ashby: AtsEntry[];
  sp500: { name: string; hqState: string | null }[];
};

export function buildCompanyRows(input: SeedInput): CompanyRow[] {
  const byKey = new Map<string, CompanyRow>();
  for (const ats of ['greenhouse', 'lever', 'ashby'] as const) {
    for (const e of input[ats]) {
      const token = (e.token ?? '').trim();
      const name = (e.name ?? '').trim();
      const key = normalizeCompany(name);
      if (!token || !name || !key || byKey.has(key)) continue;
      byKey.set(key, {
        name,
        normalized_name: key,
        ats,
        ats_token: token,
        ats_meta: ats === 'lever' && e.host === 'eu' ? { region: 'eu' } : {},
        regions: [],
        coverage: 'covered',
      });
    }
  }
  for (const s of input.sp500) {
    const name = s.name.trim();
    const key = normalizeCompany(name);
    if (!key) continue;
    const row = byKey.get(key);
    if (row) {
      if (s.hqState && !row.regions.includes(s.hqState)) row.regions.push(s.hqState);
    } else {
      byKey.set(key, {
        name,
        normalized_name: key,
        ats: 'unknown',
        ats_token: null,
        ats_meta: {},
        regions: s.hqState ? [s.hqState] : [],
        coverage: 'unknown',
      });
    }
  }
  return [...byKey.values()];
}

export function buildIndustryRows(
  rows: { name: string; sector: string; subIndustry: string }[],
): { name: string; industry: string }[] {
  const seen = new Set<string>();
  const out: { name: string; industry: string }[] = [];
  for (const r of rows) {
    const name = r.name.trim();
    const sector = r.sector.trim();
    const sub = r.subIndustry.trim();
    if (!name || !sector || seen.has(name)) continue;
    seen.add(name);
    out.push({ name, industry: sub ? `${sector} / ${sub}` : sector });
  }
  return out;
}

async function get(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

async function main() {
  const js = (a: string) =>
    get(`https://raw.githubusercontent.com/Gsync/jobsync/${JOBSYNC_SHA}/src/lib/scraper/${a}/companies.json`).then(
      (t) => JSON.parse(t) as AtsEntry[],
    );
  const [greenhouse, lever, ashby, csv] = await Promise.all([
    js('greenhouse'),
    js('lever'),
    js('ashby'),
    get(`https://raw.githubusercontent.com/datasets/s-and-p-500-companies/${SP500_SHA}/data/constituents.csv`),
  ]);
  const csvRows = parseCsv(csv);
  const sp500 = csvRows.map((r) => ({
    name: r.Security ?? '',
    hqState: stateFromLocation(r['Headquarters Location'] ?? ''),
  }));
  if (sp500.length < 400) throw new Error(`only ${sp500.length} S&P rows; refusing to write`);
  const today = new Date().toISOString().slice(0, 10);

  const industries = buildIndustryRows(
    csvRows.map((r) => ({ name: r.Security ?? '', sector: r['GICS Sector'] ?? '', subIndustry: r['GICS Sub-Industry'] ?? '' })),
  );
  if (industries.length < 400) throw new Error(`only ${industries.length} industry rows; refusing to write`);
  const indHeader =
    `-- Generated by scripts/build-companies-seed.ts --industries-only. Do not edit by hand.\n` +
    `-- Source, retrieved ${today}: datasets/s-and-p-500-companies @ ${SP500_SHA} (ODC PDDL): data/constituents.csv\n` +
    `-- Sets companies.industry ('<GICS Sector> / <GICS Sub-Industry>') and is_fortune500 (meaning "on the S&P 500 list") for matching seeded companies.\n\n`;
  const indBody = industries
    .map(
      (r) =>
        `update public.companies set industry = ${sqlText(r.industry)}, is_fortune500 = true where normalized_name = public.normalize_company(${sqlText(r.name)});\n`,
    )
    .join('');
  const indOut = 'supabase/migrations/20261109000600_company_industries.sql';
  writeFileSync(indOut, indHeader + indBody);
  console.log(`Wrote ${industries.length} industry updates to ${indOut}`);
  if (process.argv.includes('--industries-only')) return;

  const rows = buildCompanyRows({ greenhouse, lever, ashby, sp500 });
  if (rows.length < 4000 || rows.length > 8000) throw new Error(`${rows.length} companies outside 4000..8000; refusing to write`);

  const header =
    `-- Generated by scripts/build-companies-seed.ts. Do not edit by hand.\n` +
    `-- Sources, retrieved ${today}:\n` +
    `--   Gsync/jobsync @ ${JOBSYNC_SHA} (MIT, (c) 2024 gsync): src/lib/scraper/{greenhouse,lever,ashby}/companies.json\n` +
    `--   datasets/s-and-p-500-companies @ ${SP500_SHA} (ODC PDDL): data/constituents.csv\n\n`;
  const body = insertStatements(
    'public.companies',
    ['name', 'normalized_name', 'ats', 'ats_token', 'ats_meta', 'regions', 'coverage'],
    rows.map((r) => ({
      ...r,
      ats_meta: JSON.stringify(r.ats_meta),
      regions: `{${r.regions.join(',')}}`,
    })),
    'on conflict (normalized_name) do nothing',
  );
  const backfill =
    `\n-- Task 1 added companies.watchers with a trigger but no backfill.\n` +
    `update public.companies c\n` +
    `   set watchers = (select count(*) from public.user_companies uc where uc.company_id = c.id)\n` +
    ` where watchers is distinct from (select count(*) from public.user_companies uc where uc.company_id = c.id);\n`;
  const out = 'supabase/migrations/20261109000200_seed_companies.sql';
  writeFileSync(out, header + body + backfill);
  const by = (k: string) => rows.filter((r) => r.ats === k).length;
  console.log(
    `Wrote ${rows.length} companies to ${out} (greenhouse ${by('greenhouse')}, lever ${by('lever')}, ashby ${by('ashby')}, unknown ${by('unknown')})`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
