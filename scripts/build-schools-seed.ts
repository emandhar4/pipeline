// Usage: npx tsx scripts/build-schools-seed.ts   (needs SCORECARD_API_KEY in .env.local; local seed script only)
import { existsSync, writeFileSync } from 'node:fs';
import { insertStatements, toSchoolRows, type ScorecardResult } from './seed-sql';

if (existsSync('.env.local')) process.loadEnvFile('.env.local');
const key = process.env.SCORECARD_API_KEY;
if (!key) {
  console.error('Missing SCORECARD_API_KEY in .env.local (free key from https://api.data.gov/signup/).');
  process.exit(1);
}

const BASE = 'https://api.data.gov/ed/collegescorecard/v1/schools';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function fetchPage(page: number): Promise<{ results: ScorecardResult[]; total: number }> {
  const qs = new URLSearchParams({
    'school.operating': '1',
    'school.degrees_awarded.highest__range': '2..4',
    fields: 'id,school.name,school.city,school.state,school.alias',
    per_page: '100',
    page: String(page),
  });
  for (let attempt = 0; attempt <= 5; attempt++) {
    try {
      const res = await fetch(`${BASE}?${qs}`, { headers: { 'X-Api-Key': key! } });
      if (res.ok) {
        const json = (await res.json()) as { results?: ScorecardResult[]; metadata?: { total?: number } };
        if (!Array.isArray(json.results) || typeof json.metadata?.total !== 'number') {
          throw new Error('unexpected response shape');
        }
        return { results: json.results, total: json.metadata.total };
      }
      if (res.status !== 429 && res.status < 500) throw Object.assign(new Error(`HTTP ${res.status}`), { fatal: true });
      if (attempt < 5) console.error(`page ${page}: HTTP ${res.status}, retry ${attempt + 1}/5`);
    } catch (e) {
      if ((e as { fatal?: boolean }).fatal) throw e;
      if (attempt < 5) console.error(`page ${page}: ${(e as Error).message}, retry ${attempt + 1}/5`);
    }
    if (attempt === 5) break;
    await sleep(2000 * 2 ** attempt);
  }
  throw new Error(`page ${page} failed after 5 retries`);
}

async function main() {
  const all: ScorecardResult[] = [];
  let total = Infinity;
  let pages = 0;
  for (let page = 0; all.length < total; page++) {
    const { results, total: t } = await fetchPage(page);
    total = t;
    if (results.length === 0) break;
    all.push(...results);
    pages++;
    await sleep(1000);
  }
  if (all.length < total) throw new Error(`fetched ${all.length} of ${total}; refusing to write`);
  const byId = new Map(toSchoolRows(all).map((r) => [r.unitid, r]));
  const rows = [...byId.values()].sort((a, b) => a.unitid - b.unitid);
  if (rows.length < 3000 || rows.length > 7000) {
    throw new Error(`${rows.length} schools is outside the expected 3000..7000; refusing to write`);
  }
  const today = new Date().toISOString().slice(0, 10);
  const header =
    `-- Generated by scripts/build-schools-seed.ts. Do not edit by hand.\n` +
    `-- Source: US Dept of Education College Scorecard API, ${BASE}, retrieved ${today}.\n` +
    `-- License: public domain (US Government work).\n\n`;
  const body = insertStatements(
    'public.schools',
    ['unitid', 'name', 'city', 'state', 'alias'],
    rows,
    'on conflict (unitid) do update set name = excluded.name, city = excluded.city, state = excluded.state, alias = excluded.alias',
  );
  const out = 'supabase/migrations/20261108000700_seed_schools.sql';
  writeFileSync(out, header + body);
  console.log(`Fetched ${pages} pages (${all.length} results); wrote ${rows.length} schools to ${out}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
