// Usage: npx tsx scripts/build-majors-seed.ts <path-to-CIPCode2020.csv>
// Source: https://nces.ed.gov/ipeds/cipcode/Files/CIPCode2020.csv (download first; this script reads it as data only).
import { readFileSync, writeFileSync } from 'node:fs';
import { insertStatements, parseCsv, toMajorRows } from './seed-sql';

const input = process.argv[2];
if (!input) {
  console.error('Usage: npx tsx scripts/build-majors-seed.ts <path-to-CIPCode2020.csv>');
  process.exit(1);
}
const rows = toMajorRows(parseCsv(readFileSync(input, 'utf8')));
if (rows.length < 200) {
  console.error(`Only ${rows.length} majors parsed; refusing to write a seed from a suspect file.`);
  process.exit(1);
}
const today = new Date().toISOString().slice(0, 10);
const header =
  `-- Generated by scripts/build-majors-seed.ts. Do not edit by hand.\n` +
  `-- Source: NCES CIP 2020, https://nces.ed.gov/ipeds/cipcode/Files/CIPCode2020.csv, retrieved ${today}.\n` +
  `-- License: public domain (US Government work).\n\n`;
const body = insertStatements(
  'public.majors',
  ['cip_code', 'title', 'family'],
  rows,
  'on conflict (cip_code) do update set title = excluded.title, family = excluded.family',
);
const out = 'supabase/migrations/20261108000600_seed_majors.sql';
writeFileSync(out, header + body);
console.log(`Wrote ${rows.length} majors to ${out}`);
